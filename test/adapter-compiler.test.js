function assertCheckSuccess(result, context) {
  assert.ifError(result.error);
  assert.strictEqual(result.signal, null, `${context}: terminated by ${result.signal}`);
  assert.strictEqual(result.status, 0, `${context}\n${result.stdout || ''}${result.stderr || ''}`);
  assert.strictEqual(result.stderr, '', `${context}: wrote unexpected stderr`);
  assert.match(result.stdout, /^Generated adapters are current \(\d+ envelopes\)\.\n$/);
}

function staticReferenceCandidates(reference) {
  const candidates = [reference];
  if (/[.,;:!?]$/.test(reference)) candidates.push(reference.slice(0, -1));
  return candidates;
}

function assertBundleReference(plan, reference, sourcePath) {
  for (const candidate of staticReferenceCandidates(reference)) {
    assert.ok(!path.posix.isAbsolute(candidate), `${plan.id}:${sourcePath}: absolute bundle reference ${candidate}`);
    assert.ok(!candidate.split('/').includes('..'), `${plan.id}:${sourcePath}: traversing bundle reference ${candidate}`);

    const dynamicAt = candidate.search(/[{}*]/);
    if (dynamicAt !== -1) {
      const staticPrefix = candidate.slice(0, dynamicAt);
      if ([...plan.files.keys()].some((file) => file.startsWith(staticPrefix))) return;
      continue;
    }
    if (plan.files.has(candidate)) return;
    if ([...plan.files.keys()].some((file) => file.startsWith(`${candidate.replace(/\/$/, '')}/`))) return;
  }
  assert.fail(`${plan.id}:${sourcePath}: bundle reference does not resolve inside its envelope: ${reference}`);
}

function assertSelfContained(plan, nativePaths, transformProtocolReferences) {
  let references = 0;
  for (const sourcePath of nativePaths) {
    const source = planText(plan, sourcePath);
    const logical = /protocol:\/\/([A-Za-z0-9._{}*/-]+)/g;
    const rooted = /\$\{(?:extensionRoot|extensionPath|CLAUDE_PLUGIN_ROOT|PLUGIN_ROOT)\}\/([A-Za-z0-9._{}*/-]+)/g;
    for (const pattern of [logical, rooted]) {
      for (const match of source.matchAll(pattern)) {
        references++;
        assertBundleReference(plan, match[1], sourcePath);
      }
    }
    assert.doesNotMatch(source, /^@protocol:\/\//m, `${plan.id}:${sourcePath}: unresolved protocol include`);
    if (transformProtocolReferences) {
      assert.doesNotMatch(
        source,
        /protocol:\/\//,
        `${plan.id}:${sourcePath}: a native bundle reference was not rewritten`
      );
    }
  }
  assert.ok(references > 0, `${plan.id}: no bundle references were checked`);
}

function assertSkillLinksResolve(plan) {
  for (const sourcePath of planFiles(plan, /^skills\/[^/]+\/.*\.md$/)) {
    const source = planText(plan, sourcePath);
    for (const match of source.matchAll(/\[[^\]]*\]\(([^)]+)\)/g)) {
      const reference = match[1].split('#')[0];
      if (!reference || /^[a-z][a-z0-9+.-]*:/i.test(reference) || reference.startsWith('/')) continue;
      const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(sourcePath), reference));
      assert.ok(!resolved.startsWith('../'), `${plan.id}:${sourcePath}: link escapes the bundle: ${reference}`);
      assert.ok(plan.files.has(resolved), `${plan.id}:${sourcePath}: broken bundled link ${reference}`);
    }
  }
}

